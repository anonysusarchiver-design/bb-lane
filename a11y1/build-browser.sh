#!/usr/bin/env bash
# a11y1/build-browser.sh — build an OPT Linux browser from the public
# mozilla-firefox/firefox mirror pinned to a commit, with the A11Y-1 test-only
# sender + test patches applied.
#
# A11Y-1: missing detached-root guard in DocAccessibleParent::ProcessHideEvent.
# This script only produces the ARM-1 (unguarded) build; the guard probe is
# applied later by run-arm2.sh on the same tree.
#
# usage: build-browser.sh <source_rev>
# Outputs: mc/ (source), mc/obj-a11y1/dist/bin/firefox, a11y1-source-rev.txt
set -euo pipefail

SRC_REV="${1:?usage: build-browser.sh <source_rev>}"
WORK="$(pwd)"
HERE="$(cd "$(dirname "$0")" && pwd)"
OBJDIR_NAME="obj-a11y1"

echo "== runner =="
date -u
uname -a
nproc
free -h | head -2
df -h / | tail -1
(clang --version | head -2) || echo "clang: absent (bootstrap will fetch)"
python3 --version

echo "== disk pre-clean =="
sudo rm -rf /usr/share/dotnet /usr/local/lib/android /opt/ghc /opt/hostedtoolcache/CodeQL /usr/local/share/boost || true
sudo apt-get clean || true
df -h / | tail -1

echo "== apt system deps (per-package, tolerant) =="
sudo apt-get update -qq -y
PKGS=(
  m4 autoconf2.13 zlib1g-dev unzip uuid-dev pkg-config
  libgtk-3-dev libdbus-glib-1-dev libpulse-dev libasound2-dev
  libxt-dev libx11-xcb-dev libxcb-randr0-dev libxcb-shm0-dev libxcb-sync-dev
  libxcb-xfixes0-dev libxcomposite-dev libxdamage-dev libxrender-dev
  libxfixes-dev libxext-dev libxrandr-dev libglib2.0-dev libdrm-dev
  gdb xvfb fonts-liberation python3-venv python3-dev
)
for p in "${PKGS[@]}"; do
  sudo apt-get install -y -qq --no-install-recommends "$p" || echo "NOTE: dep install failed (continuing): $p"
done
echo "critical probe:"
(pkg-config --version && gdb --version | head -1 && command -v xvfb-run && echo deps-ok) || true

echo "== rust toolchain (stable, must be >= MSRV 1.90) =="
export RUSTUP_HOME="${RUSTUP_HOME:-$HOME/.rustup}"
export CARGO_HOME="${CARGO_HOME:-$HOME/.cargo}"
if ! command -v rustc >/dev/null 2>&1; then
  curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --default-toolchain stable --profile minimal
fi
# shellcheck disable=SC1091
source "$HOME/.cargo/env"
rustc --version
cargo --version
rustup component add llvm-tools-preview || true
rustup component add rustfmt || true

echo "== clone pinned source =="
rm -rf mc
git clone --depth 1 https://github.com/mozilla-firefox/firefox.git mc
git -C mc fetch --depth 1 origin "$SRC_REV"
git -C mc checkout -q FETCH_HEAD
git -C mc rev-parse HEAD | tee "$WORK/a11y1-source-rev.txt"
git -C mc log -1 --format='%H %s' || true

echo "== apply test-only patches =="
git -C mc apply --verbose "$HERE/a11y1-sender.patch"
git -C mc apply --verbose "$HERE/a11y1-test.patch"
echo "-- patch marker checks --"
grep -n "A11Y-1 FORGE" mc/accessible/generic/LocalAccessible.cpp | head -3
grep -n "test_a11y1_forge.html" mc/testing/mochitest/tests/Harness_sanity/mochitest.toml
test -f mc/testing/mochitest/tests/Harness_sanity/test_a11y1_forge.html
cp "$HERE/a11y1-sender.patch" "$HERE/a11y1-test.patch" "$HERE/a11y1-fix.patch" "$WORK/" 2>/dev/null || true

echo "== MOZCONFIG =="
mkdir -p "$HOME/mozconfigs"
cat > "$HOME/mozconfigs/a11y1" <<EOF
# generated by a11y1/build-browser.sh
ac_add_options --enable-project=browser
ac_add_options --enable-optimize
ac_add_options --disable-debug
ac_add_options --disable-crashreporter
ac_add_options --enable-bootstrap
mk_add_options MOZ_OBJDIR=@TOPSRCDIR@/$OBJDIR_NAME
EOF
cat "$HOME/mozconfigs/a11y1"
export MOZCONFIG="$HOME/mozconfigs/a11y1"
export MOZBUILD_STATE_PATH="$HOME/.mozbuild"

echo "== build (mach, browser OPT) =="
date -u
cd mc
./mach build
cd "$WORK"
date -u

BIN="mc/$OBJDIR_NAME/dist/bin/firefox"
test -x "$BIN" || { echo "BUILD-ERROR: firefox binary not found"; exit 1; }
ls -l "$BIN"
sha256sum "$BIN" | tee a11y1-binary-sha256.txt
df -h / | tail -1
echo "BUILD-OK bin=$WORK/$BIN"
