#!/usr/bin/env bash
# emz7/build-jsshell.sh — build a standalone SpiderMonkey js shell from source
# on an ubuntu GitHub runner (public mirror, no auth). Places the binary at
# <workdir>/jsshell-source/js and writes jsshell-source/js-path.txt.
#
# E-MZ-7 fork of emz5/build-jsshell.sh: adds optional THIRD arg — a mirror
# commit to pin (fetched with --depth 1 after the clone) so the built tree is
# deterministic and matches the rev the instrumentation patch was validated
# against. Empty/unset = default-branch HEAD (legacy behavior).
#
# usage: build-jsshell.sh [configure-flags-string] [patch-file] [source-rev]
#   default flags: --disable-debug --enable-optimize
#   patch-file (optional): unified diff applied to the clone with `git apply -p1`
#     before configure/build. A failed apply aborts the build loudly.
set -euo pipefail

FLAGS="${1:---disable-debug --enable-optimize}"
PATCH_FILE="${2:-}"
SRC_REV="${3:-}"
WORK="$(pwd)"
OBJDIR_NAME="obj-emz5"

echo "== free disk (pre-clean) =="
df -h / | tail -1
sudo rm -rf /usr/share/dotnet /usr/local/lib/android /opt/ghc /opt/hostedtoolcache/CodeQL /usr/local/share/boost || true
sudo apt-get clean || true
echo "== free disk (post-clean) =="
df -h / | tail -1

echo "== install build deps =="
sudo apt-get update -qq
sudo apt-get install -y -qq clang lld m4 autoconf2.13 zlib1g-dev
(clang --version | head -1) || true

echo "== clone mozilla-central (shallow, public GitHub mirror) =="
git clone --depth 1 https://github.com/mozilla-firefox/firefox.git mc
if [ -n "$SRC_REV" ]; then
  echo "== pin source rev: $SRC_REV =="
  git -C mc fetch --depth 1 origin "$SRC_REV"
  git -C mc checkout -q FETCH_HEAD
fi
git -C mc rev-parse HEAD | tee "$WORK/jsshell-source-rev.txt"

if [ -n "$PATCH_FILE" ]; then
  echo "== applying instrumentation patch: $PATCH_FILE =="
  sha256sum "$PATCH_FILE" | tee "$WORK/jsshell-patch-sha256.txt"
  if ! git -C mc apply --verbose "$PATCH_FILE"; then
    echo "PATCH-ERROR: git apply failed for $PATCH_FILE (mirror drift?)"
    exit 3
  fi
  echo "== probe markers present in patched tree: =="
  grep -rn "EMZ[67]-PROBE" mc/js/src/ | tee "$WORK/jsshell-probe-markers.txt"
  echo "== patch applied OK =="
fi

echo "== MOZCONFIG (project=js; flags: $FLAGS) =="
mkdir -p "$HOME/mozconfigs"
{
  echo "# generated by emz7/build-jsshell.sh"
  echo "ac_add_options --enable-project=js"
  # shellcheck disable=SC2086
  for f in $FLAGS; do echo "ac_add_options $f"; done
  echo "mk_add_options MOZ_OBJDIR=@TOPSRCDIR@/$OBJDIR_NAME"
} > "$HOME/mozconfigs/emz5"
cat "$HOME/mozconfigs/emz5"
export MOZCONFIG="$HOME/mozconfigs/emz5"
export MOZBUILD_STATE_PATH="$HOME/.mozbuild"

echo "== build (top-level mach, js project) =="
cd mc
./mach build
cd "$WORK"

echo "== locate shell =="
JS=$(find "mc/$OBJDIR_NAME" -type f -path "*/dist/bin/js" | head -1 || true)
if [ -z "$JS" ]; then JS=$(find mc -type f -path "*/dist/bin/js" | head -1 || true); fi
if [ -z "$JS" ]; then echo "BUILD-ERROR: js binary not found"; exit 1; fi

mkdir -p jsshell-source
cp "$JS" jsshell-source/js
chmod +x jsshell-source/js
{
  echo "$WORK/jsshell-source/js"
  echo "source=$(cat "$WORK/jsshell-source-rev.txt")"
} > jsshell-source/js-path.txt
ls -l jsshell-source/js
echo "BUILD-OK bin=$WORK/jsshell-source/js"
